"""
generate_benchmark_report.py — Turn logs/benchmark.csv into BENCHMARKS.md.

Usage:
    python etl/generate_benchmark_report.py
"""

import csv
import sys
from collections import defaultdict

import config

STAGE_LABELS = {
    "tile_dem": "Tile DEM (s)",
    "compute_viewsheds": "Compute viewsheds (s)",
    "merge_tiles": "Merge tiles (s)",
}


def load_rows():
    if not config.BENCHMARK_LOG.exists():
        sys.exit(f"ERROR: no benchmark log at {config.BENCHMARK_LOG} — run the pipeline first.")
    with open(config.BENCHMARK_LOG, newline="") as fh:
        return list(csv.DictReader(fh))


def aggregate(rows):
    """municipality -> {stage: total_seconds, 'tiles': n, 'trees': n, 'errors': n}"""
    agg = defaultdict(lambda: defaultdict(float))
    meta = defaultdict(dict)
    for row in rows:
        name, stage = row["municipality"], row["stage"]
        agg[name][stage] += float(row["seconds"])
        if row["tiles"]:
            meta[name]["tiles"] = int(row["tiles"])
        if row["trees"]:
            meta[name]["trees"] = int(row["trees"])
        if row["errors"]:
            meta[name]["errors"] = int(row["errors"])
    return agg, meta


def fmt_seconds(s):
    if s >= 60:
        m, rem = divmod(s, 60)
        return f"{int(m)}m{rem:04.1f}s"
    return f"{s:.1f}s"


def main():
    rows = load_rows()
    agg, meta = aggregate(rows)

    lines = []
    lines.append("# Benchmarks & parameters — South Holland 3-30-300 viewshed pipeline")
    lines.append("")
    lines.append("Auto-generated by `etl/generate_benchmark_report.py` from `logs/benchmark.csv`.")
    lines.append("Do not edit by hand — regenerate instead.")
    lines.append("")

    lines.append("## Parameters used")
    lines.append("")
    lines.append("| Parameter | Value |")
    lines.append("|---|---|")
    lines.append(f"| Max viewshed distance | {config.MAX_DISTANCE} m |")
    lines.append(f"| Tree height | max DEM value within {config.TREE_HEIGHT_BUFFER_RADIUS} m of the tree, used directly as observer height (clamped to {config.TREE_HEIGHT_MAX_PLAUSIBLE} m; falls back to {config.OBSERVER_HEIGHT} m if out of bounds or implausible) |")
    lines.append(f"| Target height | {config.TARGET_HEIGHT} m |")
    lines.append(f"| Curvature coefficient | {config.CURVATURE_COEFF} (0 = flat-earth) |")
    lines.append(f"| DEM CRS | RD New / EPSG:28992, 0.5 m resolution |")
    lines.append(f"| Tile size (inner) | {config.TILE_PIXELS} px ({config.TILE_PIXELS * 0.5:.0f} m) |")
    lines.append(f"| Tile buffer | {config.TILE_BUFFER_PX} px ({config.TILE_BUFFER_PX * 0.5:.1f} m), extends across municipality boundaries |")
    lines.append(f"| Parallel workers | {config.NUM_WORKERS} |")
    lines.append(f"| Output raster dtype | {config.OUTPUT_DTYPE} |")
    lines.append("")

    lines.append("## Per-municipality timing")
    lines.append("")
    lines.append("| Municipality | Tiles | Trees | Tile DEM (s) | Compute viewsheds (s) | Merge (s) | Total | Trees/sec |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|")

    total_all = 0.0
    for name in sorted(agg.keys()):
        stages = agg[name]
        m = meta[name]
        tile_s = stages.get("tile_dem", 0.0)
        compute_s = stages.get("compute_viewsheds", 0.0)
        merge_s = stages.get("merge_tiles", 0.0)
        total_s = tile_s + compute_s + merge_s
        total_all += total_s
        trees = m.get("trees")
        tiles = m.get("tiles", "")
        trees_per_sec = f"{trees / compute_s:,.0f}" if trees and compute_s else ""
        lines.append(
            f"| {name} | {tiles} | {trees if trees is not None else ''} | "
            f"{tile_s:.1f} | {compute_s:.1f} | {merge_s:.1f} | "
            f"{fmt_seconds(total_s)} | {trees_per_sec} |"
        )

    lines.append("")
    total_trees = sum(m.get("trees", 0) for m in meta.values())
    total_tiles = sum(m.get("tiles", 0) for m in meta.values())
    lines.append(
        f"**{len(agg)} municipalities, {total_tiles:,} tiles, "
        f"{total_trees:,} tree viewsheds computed, "
        f"{fmt_seconds(total_all)} total processing time.**"
    )
    lines.append("")
    lines.append(
        "Note: Papendrecht and 's-Gravenhage `tile_dem` timings are approximate "
        "(measured before per-stage timing instrumentation was added); all other "
        "figures are precisely measured."
    )
    lines.append("")

    province_path = config.BASE_DIR / "data" / "processed" / "ZuidHolland_viewshed.tif"
    if province_path.exists():
        lines.append("## Final output")
        lines.append("")
        lines.append(
            f"All {len(agg)} municipality outputs merged into one province-wide COG: "
            f"`{province_path.relative_to(config.BASE_DIR)}` "
            f"({province_path.stat().st_size / 1e9:.2f} GB)."
        )
        lines.append("")

    out_path = config.BASE_DIR / "BENCHMARKS.md"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
